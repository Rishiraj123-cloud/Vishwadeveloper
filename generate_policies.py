def md_to_html(md):
    md = md.strip()
    md = re.sub(r'(?m)^### (.*)$', r'<h3>\1</h3>', md)
    md = re.sub(r'(?m)^## (.*)$', r'<h2>\1</h2>', md)
    md = re.sub(r'(?m)^# (.*)$', r'<h1>\1</h1>', md)
    md = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', md)
    md = re.sub(r'(?m)^\* (.*)$', r'<li>\1</li>', md)
    
    # Wrap lists in <ul>
    md = re.sub(r'((?:<li>.*?</li>\n?)+)', r'<ul>\n\1</ul>', md)

    # Paragraphs
    parts = []
    for p in re.split(r'\n\n+', md):
        if p.startswith('<h') or p.startswith('<ul'):
            parts.append(p)
        else:
            p = p.replace('\n', '<br>')
            parts.append(f'<p>{p}</p>')
    return '\\n'.join(parts)


